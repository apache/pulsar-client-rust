    private static Map<String, Object> routing() {
        List<String> keys = routingKeys();
        SegmentRouter router = new SegmentRouter();
        List<List<SegmentRouter.ActiveSegment>> layouts = new ArrayList<>();
        for (int n : PARTITION_COUNTS) {
            List<SegmentRouter.ActiveSegment> segments = new ArrayList<>(n);
            for (int i = 0; i < n; i++) {
                segments.add(new SegmentRouter.ActiveSegment(i, HashRange.full(), "segment-" + i,
                        "persistent://public/default/legacy-partition-" + i, List.of(), List.of()));
            }
            layouts.add(segments);
        }

        List<Object> cases = new ArrayList<>();
        int negative = 0;
        for (String key : keys) {
            byte[] utf8 = key.getBytes(StandardCharsets.UTF_8);
            check(new String(utf8, StandardCharsets.UTF_8).equals(key), "key round-trips UTF-8");
            int raw = Murmur3_32Hash.makeRawHash(utf8);
            int masked = Murmur3_32Hash.getInstance().makeHash(utf8);
            check(masked == (raw & 0x7fffffff), "makeHash == raw & 0x7fffffff");
            check(Murmur3_32Hash.makeHashUtf8(key) == masked, "makeHashUtf8 == makeHash");
            check(ScalableTopicHashing.murmur(utf8) == raw, "ScalableTopicHashing.murmur == raw");
            int segmentHash = ScalableTopicHashing.segmentHash(raw);
            int bucketHash = ScalableTopicHashing.entryBucketHash(raw);
            check(segmentHash == SegmentRouter.segmentHash(SegmentRouter.murmur(utf8)), "segmentHash");
            check(segmentHash == SegmentRouter.hash(key), "SegmentRouter.hash");
            check(bucketHash == SegmentRouter.entryBucketHash(raw), "entryBucketHash");
            check(segmentHash == (raw >>> 16) && bucketHash == (raw & 0xffff), "hash halves");
            if (raw < 0) {
                negative++;
            }

            List<Object> partitions = new ArrayList<>();
            for (int i = 0; i < PARTITION_COUNTS.length; i++) {
                int n = PARTITION_COUNTS[i];
                long routed = router.route(key, layouts.get(i));
                check(routed == Math.floorMod(masked, n), "route == signSafeMod(masked, n)");
                partitions.add(routed);
            }

            Map<String, Object> c = new LinkedHashMap<>();
            c.put("key", key);
            c.put("key_utf8_hex", HEX.formatHex(utf8));
            c.put("raw_hash", raw);
            c.put("masked_hash", masked);
            c.put("segment_hash", segmentHash);
            c.put("bucket_hash", bucketHash);
            c.put("partitions", partitions);
            cases.add(c);
        }
        check(negative > 0, "some raw hashes are negative");

        List<Object> counts = new ArrayList<>();
        for (int n : PARTITION_COUNTS) {
            counts.add(n);
        }
        Map<String, Object> doc = new LinkedHashMap<>();
        doc.put("source", SOURCE);
        doc.put("partition_counts", counts);
        doc.put("cases", cases);
        System.out.println("routing: " + cases.size() + " cases, " + negative + " with negative raw_hash");
        return doc;
    }

    private static List<String> routingKeys() {
        LinkedHashSet<String> keys = new LinkedHashSet<>();
        keys.add("");
        String alphabet = "abcdefghijklmnop";
        String digits = "0123456789ABCDEF";
        for (int len = 1; len <= 16; len++) {
            keys.add(alphabet.substring(0, len));
            keys.add(digits.substring(0, len));
        }
        keys.addAll(List.of("a", "key", "hello", "world", "Hello, World!", "pulsar", "Apache Pulsar",
                "foo", "bar", "baz", "user-1", "user-1234", "order:42", "customer_000017", "key-0", "key-1",
                "key-2", "key-3", "The quick brown fox jumps over the lazy dog",
                "persistent://public/default/my-topic", "tenant/namespace/topic-partition-3",
                " ", "  leading and trailing  ", "\t\n\r", "\u0000", "\u0000\u0000\u0000\u0000", "\u007f"));

        keys.add("x".repeat(1024));
        keys.add("x".repeat(1023));
        keys.add("x".repeat(1025));
        StringBuilder cycle = new StringBuilder();
        for (int i = 0; i < 1024; i++) {
            cycle.append((char) ('!' + (i % 94)));
        }
        keys.add(cycle.toString());
        keys.add("é".repeat(512)); // 1 KiB of 2-byte UTF-8
        keys.add("y".repeat(4096));

        keys.addAll(List.of(
                // Latin-1 range (one Java char, two UTF-8 bytes)
                "é", "café", "ñ", "ÿ", "\u0080", " ", "ÿþ", "Größe", "naïve façade",
                // two-byte UTF-8 beyond Latin-1
                "Ω", "Ünïcödé Ωμέγα", "Привет", "שלום", "߿",
                // three-byte UTF-8
                "ࠀ", "€", "日本語", "中文键", "한국어", "キー", "�", "￾", "￿",
                // four-byte UTF-8 (surrogate pairs in Java)
                "😀", "🚀rocket", "a😀b", "👨‍👩‍👧‍👦", "𐀀", "􏿿", "𝄞 music",
                // mixed lengths of each class to hit every tail size
                "é1", "é12", "é123", "€1", "€12", "😀1", "😀12", "😀123"));

        Random rnd = new Random(SEED);
        keys.add("00000000-0000-0000-0000-000000000000");
        keys.add("ffffffff-ffff-ffff-ffff-ffffffffffff");
        for (int i = 0; i < UUID_KEYS; i++) {
            long hi = (rnd.nextLong() & ~0xf000L) | 0x4000L;
            long lo = (rnd.nextLong() & 0x3fffffffffffffffL) | 0x8000000000000000L;
            String uuid = new UUID(hi, lo).toString();
            keys.add(i % 8 == 7 ? uuid.toUpperCase() : uuid);
        }

        for (int i = 0; i < RANDOM_KEYS; i++) {
            int len = rnd.nextInt(10) == 0 ? rnd.nextInt(300) : rnd.nextInt(40);
            StringBuilder sb = new StringBuilder(len);
            int flavor = rnd.nextInt(4);
            for (int j = 0; j < len; j++) {
                sb.appendCodePoint(randomCodePoint(rnd, flavor));
            }
            keys.add(sb.toString());
        }
        return new ArrayList<>(keys);
    }

    /** A valid Unicode scalar value (never a lone surrogate). Flavor 0 keeps keys alphanumeric. */
    private static int randomCodePoint(Random rnd, int flavor) {
        if (flavor == 0) {
            String alnum = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_:.";
            return alnum.charAt(rnd.nextInt(alnum.length()));
        }
        int r = rnd.nextInt(100);
        if (r < 65) {
            return 0x20 + rnd.nextInt(0x7f - 0x20);
        } else if (r < 70) {
            return rnd.nextInt(0x20);
        } else if (r < 80) {
            return 0x80 + rnd.nextInt(0x80);
        } else if (r < 85) {
            return 0x100 + rnd.nextInt(0x800 - 0x100);
        } else if (r < 93) {
            int cp;
            do {
                cp = 0x800 + rnd.nextInt(0x10000 - 0x800);
            } while (cp >= 0xd800 && cp <= 0xdfff);
            return cp;
        } else {
            return 0x10000 + rnd.nextInt(0x110000 - 0x10000);
        }
    }

