    /** A minimal pretty-printer: objects one field per line, arrays of scalars on one line. */
    private static final class Json {

        static void write(StringBuilder sb, Object v, int indent) {
            if (v == null) {
                sb.append("null");
            } else if (v instanceof String s) {
                string(sb, s);
            } else if (v instanceof Long || v instanceof Integer || v instanceof Boolean) {
                sb.append(v);
            } else if (v instanceof Map<?, ?> map) {
                if (map.isEmpty()) {
                    sb.append("{}");
                    return;
                }
                sb.append("{\n");
                int i = 0;
                for (var e : map.entrySet()) {
                    pad(sb, indent + 1);
                    string(sb, (String) e.getKey());
                    sb.append(": ");
                    write(sb, e.getValue(), indent + 1);
                    sb.append(++i < map.size() ? ",\n" : "\n");
                }
                pad(sb, indent);
                sb.append('}');
            } else if (v instanceof List<?> list) {
                if (list.isEmpty()) {
                    sb.append("[]");
                    return;
                }
                boolean scalars = list.stream().noneMatch(x -> x instanceof Map || x instanceof List);
                if (scalars) {
                    sb.append('[');
                    for (int i = 0; i < list.size(); i++) {
                        if (i > 0) {
                            sb.append(", ");
                        }
                        write(sb, list.get(i), indent);
                    }
                    sb.append(']');
                    return;
                }
                sb.append("[\n");
                for (int i = 0; i < list.size(); i++) {
                    pad(sb, indent + 1);
                    write(sb, list.get(i), indent + 1);
                    sb.append(i + 1 < list.size() ? ",\n" : "\n");
                }
                pad(sb, indent);
                sb.append(']');
            } else {
                throw new IllegalArgumentException("unsupported JSON value " + v.getClass());
            }
        }

        private static void pad(StringBuilder sb, int indent) {
            sb.append("  ".repeat(indent));
        }

        private static void string(StringBuilder sb, String s) {
            sb.append('"');
            for (int i = 0; i < s.length(); i++) {
                char c = s.charAt(i);
                switch (c) {
                    case '"' -> sb.append("\\\"");
                    case '\\' -> sb.append("\\\\");
                    case '\n' -> sb.append("\\n");
                    case '\r' -> sb.append("\\r");
                    case '\t' -> sb.append("\\t");
                    default -> {
                        if (c < 0x20 || c == 0x7f) {
                            sb.append(String.format("\\u%04x", (int) c));
                        } else {
                            sb.append(c);
                        }
                    }
                }
            }
            sb.append('"');
        }
    }
